/** Les jeux de textes livrés, par code de langue. */
export const NG_TABLE_LOCALES: Readonly<Record<'fr' | 'en' | 'es' | 'de' | 'ar', NgTableLabels>> = {
  fr: NG_TABLE_DEFAULT_LABELS,
  en: NG_TABLE_LABELS_EN,
  es: NG_TABLE_LABELS_ES,
  de: NG_TABLE_LABELS_DE,
  ar: NG_TABLE_LABELS_AR,
};

/**
 * Textes d'une langue (`'fr-CA'`, `'de'`, `'ar-EG'`... : seule la partie avant le tiret compte), ou le français si elle
 * n'est pas livrée.
 */
export function ngTableLabelsFor(locale: string): NgTableLabels {
  const language = locale.toLowerCase().split(/[-_]/)[0] as keyof typeof NG_TABLE_LOCALES;
  return NG_TABLE_LOCALES[language] ?? NG_TABLE_DEFAULT_LABELS;
}

/** `true` pour une langue qui se lit de droite à gauche (arabe, hébreu, persan, ourdou...). */
export function ngTableIsRtl(locale: string): boolean {
  return ['ar', 'he', 'fa', 'ur', 'ps', 'sd', 'ug', 'yi', 'dv'].includes(locale.toLowerCase().split(/[-_]/)[0]);
}
